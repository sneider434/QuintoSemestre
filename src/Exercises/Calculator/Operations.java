package Exercises.Calculator;

public class Operations {

    public double toAdd(double valor1, double valor2){
        return valor1 + valor2;
    }
    public double subtraction(double valor1, double valor2){
        return valor1 - valor2;
    }
    public double multiplicacion(double valor1, double valor2){
        return valor1 * valor2;
    }
    public double division(double valor1, double valor2){
        return valor1 / valor2;
    }



}
